import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

// Mechanical conversion: keep the source link tree, URDF joint-frame RPY,
// axes, limits, link masses, centres of mass and full inertia tensors.
// The fixed base is deliberate: this demo does not simulate mobile navigation.
const attr=(source,tag,key,fallback='')=>source.match(new RegExp(`<${tag}\\b[^>]*\\b${key}="([^"]+)"`))?.[1]??fallback;
const values=s=>s.trim().split(/\s+/).map(Number);
const number=n=>Number(n.toPrecision(14)).toString();
const vector=v=>v.map(number).join(' ');
function rpyQuaternion(rpy){
  const [r,p,y]=values(rpy).map(v=>v/2),cr=Math.cos(r),sr=Math.sin(r),cp=Math.cos(p),sp=Math.sin(p),cy=Math.cos(y),sy=Math.sin(y);
  return vector([cr*cp*cy+sr*sp*sy,sr*cp*cy-cr*sp*sy,cr*sp*cy+sr*cp*sy,cr*cp*sy-sr*sp*cy]);
}
export function convertURDF(xml){
  const links=new Map([...xml.matchAll(/<link\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/link>/g)].map(([,name,body])=>[name,{name,body,children:[]}]));
  const joints=[...xml.matchAll(/<joint\s+name="([^"]+)"\s+type="([^"]+)"[^>]*>([\s\S]*?)<\/joint>/g)].map(([,name,type,body])=>({name,type,body,parent:attr(body,'parent','link'),child:attr(body,'child','link')}));
  for(const j of joints)links.get(j.parent).children.push(j);
  const aliasJoint=j=>j.name.replace(/_gripper_finger_joint(\d)/,'_finger$1');
  const aliasLink=name=>name.replace(/_gripper_finger_link(\d)/,'_pad$1');
  const motors=[];
  const emitLink=(name,joint,depth)=>{
    const link=links.get(name),indent='  '.repeat(depth),lines=[];
    const pose=joint?` pos="${attr(joint.body,'origin','xyz','0 0 0')}" quat="${rpyQuaternion(attr(joint.body,'origin','rpy','0 0 0'))}"`:'';
    lines.push(`${indent}<body name="${aliasLink(name)}"${pose}>`);
    if(joint&&joint.type!=='fixed'){
      const finger=joint.type==='prismatic',range=joint.type==='continuous'?' limited="false"':` range="${attr(joint.body,'limit','lower','0')} ${attr(joint.body,'limit','upper','0')}"`;
      lines.push(`${indent}  <joint name="${aliasJoint(joint)}" type="${finger?'slide':'hinge'}" axis="${attr(joint.body,'axis','xyz','0 0 1')}"${range} damping="${finger?1:.02}" armature="0.005"/>`);
      const effort=Number(attr(joint.body,'limit','effort',finger?'5':'44'));
      if(finger){
        const prefix=joint.name.split('_')[0],index=joint.name.at(-1);
        motors.push(`<position name="${prefix}_motor${index}" joint="${aliasJoint(joint)}" kp="350" kv="3" forcelimited="true" forcerange="-5 5" ctrlrange="0 .05"/>`);
      }else{
        const torso=joint.name.startsWith('torso_'),arm=joint.name.includes('_arm_'),index=Number(joint.name.at(-1));
        const kp=torso?24000:arm?[0,4500,4500,2500,700,700,450][index]:1500;
        const kv=torso?550:arm?[0,90,90,55,14,14,9][index]:15;
        motors.push(`<general name="${joint.name}_motor" joint="${joint.name}" gainprm="1" biastype="affine" biasprm="0 -${kp} -${kv}" forcelimited="true" forcerange="-${effort} ${effort}"/>`);
      }
    }
    const inertial=link.body.match(/<inertial>([\s\S]*?)<\/inertial>/)?.[1];
    if(inertial){
      if(values(attr(inertial,'origin','rpy','0 0 0')).some(v=>Math.abs(v)>1e-12))throw new Error(`Inertia rotation needs tensor rotation: ${name}`);
      const inertia=['ixx','iyy','izz','ixy','ixz','iyz'].map(key=>attr(inertial,'inertia',key));
      lines.push(`${indent}  <inertial pos="${attr(inertial,'origin','xyz','0 0 0')}" mass="${attr(inertial,'mass','value')}" fullinertia="${inertia.join(' ')}"/>`);
    }
    if(name.includes('_gripper_finger_link')){
      const arm=name.split('_')[0],i=Number(name.at(-1)),sign=(arm==='right'?[-1,1]:[1,-1])[i-1],origin=values(attr(joint.body,'origin','xyz','0 0 0'));
      // Fixed-size fingertip contact proxy expressed in the actual URDF
      // finger frame; neither its size nor its pose changes while closing.
      const local=[.068-origin[0],sign*.004-origin[1],-origin[2]];
      lines.push(`${indent}  <geom name="${arm}_tip${i}" type="box" pos="${vector(local)}" size=".012 .004 .0065" contype="2" conaffinity="1"/>`);
    }
    for(const child of link.children)lines.push(emitLink(child.child,child,depth+1));
    lines.push(`${indent}</body>`);return lines.join('\n');
  };
  const tree=emitLink('base_link',null,2);
  return `<mujoco model="r1_articulated_grasp">
  <!-- Generated by work/build-r1-dynamics.mjs from assets/r1.urdf.
       Exact URDF frames, axes, masses, COM and inertia tensors.
       Fixed base; robot shell/self contacts are omitted. Only fixed-size
       fingertip boxes collide with task objects. Meshes remain visual URDF.
       All movable joints are actuated; no mocap, weld, support or attachment. -->
  <compiler angle="radian" autolimits="true" fusestatic="false"/>
  <option timestep=".001" integrator="implicitfast" solver="Newton" iterations="60" cone="elliptic" gravity="0 0 -9.81"/>
  <default><geom contype="0" conaffinity="0" friction="3.5 .08 .01" solref=".006 1" solimp=".95 .99 .001" condim="6"/></default>
  <worldbody>
    <geom name="floor" type="plane" size="3 3 .1" contype="1" conaffinity="3"/>
    <body name="task_table" pos=".78 0 .6595"><geom name="table_top" type="box" size=".36 .38 .0325" contype="1" conaffinity="3"/></body>
    <body name="red_cube" pos=".78 -.14 .7145"><freejoint/><geom type="box" size=".0225 .0225 .0225" mass=".045" contype="1" conaffinity="3"/></body>
    <body name="blue_block" pos=".78 0 .711"><freejoint/><geom type="box" size=".026 .016 .019" mass=".050" contype="1" conaffinity="3"/></body>
    <body name="yellow_cylinder" pos=".78 .14 .718"><freejoint/><geom type="cylinder" size=".020 .026" mass=".042" contype="1" conaffinity="3"/></body>
${tree}
  </worldbody>
  <contact><exclude body1="right_pad1" body2="right_pad2"/><exclude body1="left_pad1" body2="left_pad2"/></contact>
  <actuator>
${motors.map(m=>'    '+m).join('\n')}
  </actuator>
</mujoco>\n`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
  const source=await readFile(new URL('../dist/r1/assets/r1.urdf',import.meta.url),'utf8');
  const output=convertURDF(source),target=new URL('../dist/r1/models/r1-dynamic-scene.xml',import.meta.url);
  await writeFile(target,output);console.log(`Generated ${fileURLToPath(target)} (${output.length} bytes)`);
}
